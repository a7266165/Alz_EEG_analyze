# 3. 建立 Info + standard_1020 montage
montage = mne.channels.make_standard_montage('standard_1020')
info    = mne.create_info(ch_names=ch_names, sfreq=256, ch_types='eeg')
info.set_montage(montage)

# 4. 繪圖：2×7，縮小尺寸
fig, axes = plt.subplots(2, 7, figsize=(14, 4))

# 5. 繪製每一張 topomap
for row, data_dict in enumerate((abs_data, rel_data)):
    for col, (band, vals) in enumerate(data_dict.items()):
        # 將vals所有值改為 1 - p-value
        vals = [1 - val for val in vals]
        inv = np.array(vals) 
        ax  = axes[row, col]
        mne.viz.plot_topomap(inv, info, axes=ax, show=False,
                             cmap='jet',       # RGB 彩虹
                             vlim=(0, 1),
                             contours=0)
        # 第 1 排才畫頻帶名稱作為 column title
        if row == 0:
            ax.set_title(band, fontsize=9)
        # 只去掉內部 tick
        ax.set_xticks([]); ax.set_yticks([])

    # 在最左邊那格加上 row label
    label = 'Absolute' if row == 0 else 'Relative'
    axes[row, 0].set_ylabel(label, rotation=0, labelpad=30, va='center', fontsize=12)

# 6. 全域 colorbar，並把標題放在上方
